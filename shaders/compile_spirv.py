#!/usr/bin/env python3
"""Regenerate src/microui_spv.h from the GLSL sources in this directory.

Requires glslangValidator (e.g. `brew install glslang`). The generated header
is committed so that building the project itself has no shader-tool dependency.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "microui_spv.h"
STAGES = ("vert", "frag")

def main() -> int:
    glslang = shutil.which("glslangValidator")
    if not glslang:
        print("error: glslangValidator not found; install with `brew install glslang`", file=sys.stderr)
        return 1

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        spv = {}
        for stage in STAGES:
            src = HERE / f"microui.{stage}.glsl"
            dst = tmp / f"microui.{stage}.spv"
            subprocess.run([glslang, "-V", str(src), "-o", str(dst)], check=True)
            spv[stage] = dst.read_bytes()

    lines = []
    lines.append("/* Auto-generated by shaders/compile_spirv.py — do not edit by hand.")
    lines.append(" * SPIR-V bytecode for the microui UI shaders (Vulkan backend).")
    lines.append(" * Regenerate with:  python3 shaders/compile_spirv.py")
    lines.append(" */")
    lines.append("#ifndef MICROUI_SPV_H")
    lines.append("#define MICROUI_SPV_H")
    lines.append("")
    lines.append("#include <SDL3/SDL.h>")
    lines.append("")
    for stage in STAGES:
        data = spv[stage]
        lines.append(f"static const Uint8 mu_spv_{stage}[] = {{")
        row = "    "
        for i, b in enumerate(data):
            row += f"0x{b:02x}, "
            if (i + 1) % 12 == 0:
                lines.append(row)
                row = "    "
        if row.strip():
            lines.append(row)
        lines.append("};")
        lines.append(f"static const size_t mu_spv_{stage}_len = {len(data)};")
        lines.append("")
    lines.append("#endif /* MICROUI_SPV_H */")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
